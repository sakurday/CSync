"""Generate embedded UI icons from the user-supplied Google Material SVGs.

Run after replacing files in icons/. Original downloads remain unchanged.
All UI symbols come from icons/ and are shared by both UIs.
"""
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
DRAWABLE = ROOT / "android/app/src/main/res/drawable"
SVG = "{http://www.w3.org/2000/svg}"


def generate():
    symbols = {}
    for name in ("settings", "mobile", "menu", "error", "delete", "check_circle",
                 "sync", "computer", "add", "chevron_right", "qr_code", "qr_code_scanner"):
        source = ROOT / "icons" / f"{name}_24dp_E3E3E3_FILL0_wght400_GRAD0_opsz24.svg"
        svg = ET.parse(source).getroot()
        assert svg.attrib["viewBox"] == "0 0 24 24", source
        paths = [p.attrib["d"] for p in svg.findall(f"{SVG}path")]
        assert paths, source
        symbols[name] = paths
        # Compose supplies tint from MaterialTheme; preserve geometry, not download color.
        target = "drag_handle" if name == "menu" else name
        if name != "mobile":
            body = "\n".join(f'    <path android:fillColor="#FF000000" android:pathData="{p}" />' for p in paths)
            mirrored = ' android:autoMirrored="true"' if name == "chevron_right" else ''
            (DRAWABLE / f"ic_material_{target}.xml").write_text(
                '<!-- Generated by scripts/generate-material-icons.py from icons/; do not edit. -->\n'
                '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24"'
                + mirrored + '>\n'
                + body + '\n</vector>\n', encoding="utf-8")
    output = '// Generated by scripts/generate-material-icons.py. No runtime files or fonts.\n'
    output += 'const paths = ' + json.dumps(symbols, ensure_ascii=False, indent=2) + ';\n'
    output += '''export function materialIcon(name, document = globalThis.document) {
  if (!paths[name]) throw new Error(`Unknown Material icon: ${name}`);
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', '24');
  svg.setAttribute('height', '24');
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  for (const data of paths[name]) {
    const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
    path.setAttribute('d', data);
    svg.append(path);
  }
  return svg;
}
'''
    (ROOT / "crates/csync-windows/web/material-icons.mjs").write_text(output, encoding="utf-8")
    print("Generated Android vectors and embedded Web SVGs from icons/.")


if __name__ == "__main__":
    generate()
